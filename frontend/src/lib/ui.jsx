// Styled like a Malaysian number plate: white characters on black.
export function Plate({ children, size = 'md' }) {
  return <span className={`plate plate-${size}`}>{children}</span>;
}

// Bookings are confirmed on creation; what changes is where the trip is.
export function tripState(b) {
  if (b.checkedOutAt) return 'done';
  if (b.checkedInAt) return 'inuse';
  return 'booked';
}

const STATE_LABEL = { booked: 'Booked', inuse: 'In use', done: 'Returned', available: 'Available' };

export function StatusPill({ state }) {
  return <span className={`pill pill-${state}`}>{STATE_LABEL[state] || state}</span>;
}

const pad = (n) => String(n).padStart(2, '0');

export const fmtDT = (s) => new Date(s).toLocaleString('en-GB', { weekday: 'short', day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
export const fmtDTY = (s) => new Date(s).toLocaleString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });
export const fmtTime = (s) => new Date(s).toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' });

// "Tue 28 Oct, 09:00 – 17:00" when the trip is one day, otherwise both ends in full.
export function fmtRange(s, e) {
  const a = new Date(s), b = new Date(e);
  if (a.toDateString() === b.toDateString()) return `${fmtDT(s)} – ${fmtTime(e)}`;
  return `${fmtDT(s)} → ${fmtDT(e)}`;
}

export const toLocalInput = (d) =>
  `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;

export const bookingRef = (id) => `#R${String(id).padStart(3, '0')}`;
